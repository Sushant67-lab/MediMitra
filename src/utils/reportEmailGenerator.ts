import { TriageAssessment, UserProfile } from '../types/medical';
import { COMMON_SYMPTOMS } from '../data/medicalKnowledge';

export function formatReportText(
  assessment: TriageAssessment,
  currentProfile: UserProfile,
  reportId: string
): { subject: string; body: string } {
  const symptomInfo = COMMON_SYMPTOMS.find(s => s.id === assessment.primarySymptom) || COMMON_SYMPTOMS[0];
  const isSevere = assessment.severity === 'emergency' || assessment.severity === 'severe';

  const subject = `MediMitra Health Report: ${currentProfile.name} - ${symptomInfo.name} [${reportId}]`;

  const medicinesSection = !isSevere && assessment.recommendedOtcs.length > 0
    ? assessment.recommendedOtcs.map((otc, idx) => 
        `${idx + 1}. ${otc.name} (${otc.category})\n   - Dosage: ${otc.dosageGuide}\n   ${otc.childDosageNote ? `- Pediatric note: ${otc.childDosageNote}\n   ` : ''}- Caution: ${otc.safetyCaution}`
      ).join('\n\n')
    : 'No home medications recommended due to severity. Immediate doctor examination required.';

  const doctorsSection = assessment.recommendedDoctors.slice(0, 2).map((doc, idx) =>
    `${idx + 1}. ${doc.name} (${doc.specialty})\n   - Hospital: ${doc.hospital}\n   - Distance: ${doc.distanceKm} km\n   - Address: ${doc.address}\n   - Phone: ${doc.phone}`
  ).join('\n\n');

  const body = `Dear ${currentProfile.name},

Here is your digital health check-up report generated by MediMitra.

==================================================
MEDIMITRA DIGITAL HEALTHCARE REPORT
Report ID: ${reportId}
Date: ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
==================================================

1. PATIENT DEMOGRAPHICS:
- Patient Name: ${currentProfile.name}
- Age Category: ${currentProfile.ageCategory.toUpperCase()} (${currentProfile.age} years)
- Gender: ${currentProfile.sex}
- Chief Complaint: ${symptomInfo.name}

2. TRIAGE STATUS & EVALUATION:
- Clinical Level: ${isSevere ? 'SEVERE - IN-PERSON DOCTOR VISIT REQUIRED' : 'MILD / BASIC PROBLEM - SAFE FOR HOME CARE'}
- Evaluation Summary:
${assessment.clinicalSummary}

3. RECOMMENDED BASIC OTC MEDICINE:
${medicinesSection}

4. SUPPORTIVE HOME CARE MEASURES:
- Drink plenty of warm fluids, water, and oral electrolyte broths.
- Get adequate rest and minimize heavy screen time or physical exertion.
- If symptoms worsen or do not subside in 48 hours, consult a physician promptly.

5. RECOMMENDED NEAREST DOCTORS & CLINICS:
${doctorsSection}

==================================================
* MEDICAL DISCLAIMER:
This digital summary was prepared by MediMitra for informational triage guidance. It is not an official prescription or surgical clearance. For life-threatening symptoms, please contact emergency services (112 / 911) or visit the nearest emergency room immediately.
==================================================
`;

  return { subject, body };
}

/**
 * Downloads a standard RFC 822 .eml file formatted for any email client
 */
export function downloadEmlFile(
  assessment: TriageAssessment,
  currentProfile: UserProfile,
  reportId: string,
  recipientEmail: string
): void {
  const { subject, body } = formatReportText(assessment, currentProfile, reportId);

  const emlContent = [
    `To: ${recipientEmail}`,
    `Subject: ${subject}`,
    `X-Unsent: 1`,
    `Content-Type: text/plain; charset=utf-8`,
    `Date: ${new Date().toUTCString()}`,
    ``,
    body
  ].join('\r\n');

  const blob = new Blob([emlContent], { type: 'message/rfc822' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `MediMitra_Report_${reportId}.eml`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Opens Gmail Web compose with recipient, subject, and body pre-filled
 */
export function openGmailCompose(
  assessment: TriageAssessment,
  currentProfile: UserProfile,
  reportId: string,
  recipientEmail: string
): void {
  const { subject, body } = formatReportText(assessment, currentProfile, reportId);
  const url = `https://mail.google.com/mail/?view=cm&fs=1&to=${encodeURIComponent(recipientEmail)}&su=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  window.open(url, '_blank', 'noopener,noreferrer');
}

/**
 * Opens the native mailto handler
 */
export function openNativeMailto(
  assessment: TriageAssessment,
  currentProfile: UserProfile,
  reportId: string,
  recipientEmail: string
): void {
  const { subject, body } = formatReportText(assessment, currentProfile, reportId);
  const mailtoUrl = `mailto:${encodeURIComponent(recipientEmail)}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  window.location.href = mailtoUrl;
}
